# ყუთში ეტევა 12 კანფეტი
candy_per_box = 12

total_candies = int(input("შეიყვანეთ კანფეტების საერთო რაოდენობა: "))

# A. სულ რამდენი ყუთი გაივსება (მთელი ნაწილით გაყოფა)
filled_boxes = total_candies // candy_per_box

# B. რამდენი კანფეტი დარჩება (ნაშთიანი გაყოფა)
remaining_candies = total_candies % candy_per_box

print(f"A. სულ გაივსება: {filled_boxes} ყუთი")
print(f"B. ყუთების მიღმა დარჩება: {remaining_candies} კანფეტი")


total_minutes = int(input("შეიყვანეთ წუთების რაოდენობა: "))

