# 1. მიმატება (+) - ამატებს ორ რიცხვს ერთმანეთს
sum_result = 5 + 3  # შედეგი: 8

# 2. გამოკლება (-) - აკლებს მეორე რიცხვს პირველს
sub_result = 5 - 3  # შედეგი: 2

# 3. გამრავლება (*) - ამრავლებს ორ რიცხვს ერთმანეთზე
mul_result = 5 * 3  # შედეგი: 15

# 4. გაყოფა (/) - ყოფს პირველ რიცხვს მეორეზე და პასუხი ყოველთვის ათწილადია (float)
div_result = 5 / 2  # შედეგი: 2.5

# 5. მთელი ნაწილით გაყოფა (//) - ყოფს რიცხვებს და ტოვებს მხოლოდ განაყოფის მთელ ნაწილს
floor_div = 5 // 2  # შედეგი: 2

# 6. ნაშთიანი გაყოფა (%) - აბრუნებს გაყოფისას მიღებულ ნაშთს
mod_result = 5 % 2  # შედეგი: 1 (რადგან 5 გაყოფილი 2-ზე არის 2, და ნაშთში რჩება 1)

# 7. ახარისხება (**) - პირველ რიცხვს აყვანს მეორის ხარისხში
pow_result = 2 ** 3  # შედეგი: 8 (2-ის კუბი)



# მომხმარებელს შემოაქვს რიცხვი (ვიყენებთ float-ს, რომ ათწილადებიც მიიღოს)
number = float(input("შეიყვანეთ რიცხვი: "))

